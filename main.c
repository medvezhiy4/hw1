/*
 * Домашнее задание 1. Обработка одномерного массива.
 * Вариант 5: «Удаление повторений» - формируем новый массив,
 * в котором каждое значение исходного массива встречается только один раз.
 *
 * Компиляция: gcc main.c -Wall -Wextra -Wpedantic -std=c11 -o homework1
 */

#include <stdio.h> // printf, scanf
#include <stdlib.h> // exit - завершение программы при неверном вводе элементов

#define MAX_SIZE 100 // максимальный размер массива по условию задачи

// ---------- Прототипы функций ----------
void inputArray(int array[], int size); // ввод с клавиатуры
void printArray(const int array[], int size); // вывод в одну строку
int findMin(const int array[], int size); // минимальный элемент
int findMax(const int array[], int size); // максимальный элемент
int findFirstIndex(const int array[], int size, int value); // первый индекс значения
long long calculateSum(const int array[], int size); // сумма элементов
double calculateAverage(const int array[], int size); // среднее арифметическое
void printSignCounts(const int array[], int size); // сколько >0, <0 и =0
void printParityCounts(const int array[], int size); // сколько чётных и нечётных
void printInRange(const int array[], int size, int a, int b); // элементы из диапазона [a, b]
void performIndividualTask(const int array[], int size); // вариант 5: без повторений

int main(void)
{
    int array[MAX_SIZE]; // исходный массив (с запасом на максимальный размер)
    int size; // сколько элементов вводит пользователь
    int minValue; // минимальный элемент массива
    int maxValue; // максимальный элемент массива
    int a; // левая граница диапазона
    int b; // правая граница диапазона

    // 1. Запрашиваем размер массива и проверяем его допустимость.
    // Если scanf не прочитал число или число вне диапазона 1..100 - выходим.
    printf("Введите размер массива от 1 до %d: ", MAX_SIZE);
    if (scanf("%d", &size) != 1 || size < 1 || size > MAX_SIZE)
    {
        printf("Ошибка: недопустимый размер массива (допустимо от 1 до %d).\n", MAX_SIZE);
        return 1; // массив не вводим и не обрабатываем
    }

    // 2. Вводим элементы и выводим исходный массив в одной строке.
    inputArray(array, size);
    printf("Исходный массив:");
    printArray(array, size);

    // 3. Минимум и максимум. Индекс ищем отдельной функцией (первое вхождение).
    minValue = findMin(array, size);
    maxValue = findMax(array, size);
    printf("Минимальный элемент: %d (первый индекс: %d)\n",
           minValue, findFirstIndex(array, size, minValue));
    printf("Максимальный элемент: %d (первый индекс: %d)\n",
           maxValue, findFirstIndex(array, size, maxValue));

    // 4. Сумма элементов и среднее арифметическое (вещественное число).
    printf("Сумма элементов: %lld\n", calculateSum(array, size));
    printf("Среднее арифметическое: %.2f\n", calculateAverage(array, size));

    // 5. Количество положительных, отрицательных, нулевых, чётных и нечётных.
    printSignCounts(array, size);
    printParityCounts(array, size);

    // 6. Запрашиваем границы диапазона [a, b] и выводим элементы из него.
    printf("Введите границы диапазона a и b через пробел: ");
    if (scanf("%d %d", &a, &b) != 2)
    {
        printf("Ошибка: границы диапазона должны быть целыми числами.\n");
        return 1;
    }
    printInRange(array, size, a, b);

    // 7. Индивидуальное задание (вариант 5): удаление повторений.
    performIndividualTask(array, size);

    return 0; // программа завершилась успешно
}

// ---------- Ввод и вывод ----------

/*
 * Вводит size целых чисел с клавиатуры в массив array.
 * Если введено не целое число - сообщает об ошибке и завершает программу.
 */
void inputArray(int array[], int size)
{
    int i; // индекс элемента, который вводим

    printf("Введите элементы массива (количество: %d): ", size);

    for (i = 0; i < size; i++)
    {
        // scanf возвращает 1, только если удалось прочитать одно целое число
        if (scanf("%d", &array[i]) != 1)
        {
            printf("Ошибка: элементы массива должны быть целыми числами.\n");
            exit(1); // завершаем программу с кодом ошибки (как return 1 в main)
        }
    }
}

/*
 * Выводит size элементов массива в одной строке через пробел.
 * Пробел печатается ПЕРЕД числом, поэтому подпись перед вызовом
 * пишется без пробела на конце (например, "Исходный массив:").
 */
void printArray(const int array[], int size)
{
    int i; // индекс выводимого элемента

    for (i = 0; i < size; i++)
    {
        printf(" %d", array[i]);
    }

    printf("\n"); // переход на новую строку после последнего элемента
}

// ---------- Основная обработка ----------

/* Возвращает минимальный элемент массива (size >= 1). */
int findMin(const int array[], int size)
{
    int min = array[0]; // пока считаем минимальным первый элемент
    int i; // индекс сравниваемого элемента

    // Сравниваем со вторым, третьим и так далее до конца массива
    for (i = 1; i < size; i++)
    {
        if (array[i] < min)
        {
            min = array[i]; // нашли элемент меньше - запоминаем его
        }
    }

    return min;
}

/* Возвращает максимальный элемент массива (size >= 1). */
int findMax(const int array[], int size)
{
    int max = array[0]; // пока считаем максимальным первый элемент
    int i; // индекс сравниваемого элемента

    // Сравниваем со вторым, третьим и так далее до конца массива
    for (i = 1; i < size; i++)
    {
        if (array[i] > max)
        {
            max = array[i]; // нашли элемент больше - запоминаем его
        }
    }

    return max;
}

/*
 * Возвращает индекс ПЕРВОГО элемента, равного value.
 * Если такого элемента нет - возвращает -1 (в нашей программе
 * value всегда взято из массива, так что -1 не встретится).
 */
int findFirstIndex(const int array[], int size, int value)
{
    int i; // индекс проверяемого элемента

    for (i = 0; i < size; i++)
    {
        if (array[i] == value)
        {
            return i; // нашли первое совпадение - сразу возвращаем его индекс
        }
    }

    return -1; // значение не найдено
}

/* Возвращает сумму всех элементов массива. */
long long calculateSum(const int array[], int size)
{
    long long sum = 0; // long long, чтобы сумма не переполнилась
    int i; // индекс прибавляемого элемента

    for (i = 0; i < size; i++)
    {
        sum += array[i]; // прибавляем очередной элемент к сумме
    }

    return sum;
}

/*
 * Возвращает среднее арифметическое элементов (вещественное число).
 * Деления на ноль нет: main гарантирует, что size >= 1.
 */
double calculateAverage(const int array[], int size)
{
    // (double) делает деление вещественным, иначе дробная часть потерялась бы
    return (double)calculateSum(array, size) / size;
}

/* Считает и выводит количество положительных, отрицательных и нулевых элементов. */
void printSignCounts(const int array[], int size)
{
    int positive = 0; // счётчик положительных элементов
    int negative = 0; // счётчик отрицательных элементов
    int zero = 0; // счётчик нулевых элементов
    int i; // индекс проверяемого элемента

    for (i = 0; i < size; i++)
    {
        if (array[i] > 0)
        {
            positive++;
        }
        else if (array[i] < 0)
        {
            negative++;
        }
        else
        {
            zero++; // остался единственный вариант - элемент равен нулю
        }
    }

    printf("Положительных: %d, отрицательных: %d, нулевых: %d\n", positive, negative, zero);
}

/* Считает и выводит количество чётных и нечётных элементов. */
void printParityCounts(const int array[], int size)
{
    int even = 0; // счётчик чётных элементов
    int odd = 0; // счётчик нечётных элементов
    int i; // индекс проверяемого элемента

    for (i = 0; i < size; i++)
    {
        // Остаток от деления на 2 равен 0 - число чётное.
        // Нечётное проверяем через else, а не через "% 2 == 1":
        // у отрицательных нечётных чисел остаток равен -1.
        if (array[i] % 2 == 0)
        {
            even++;
        }
        else
        {
            odd++;
        }
    }

    printf("Чётных: %d, нечётных: %d\n", even, odd);
}

/* Выводит элементы массива, принадлежащие диапазону [a, b] (границы входят). */
void printInRange(const int array[], int size, int a, int b)
{
    int count = 0; // сколько элементов попало в диапазон
    int i; // индекс проверяемого элемента

    printf("Элементы из диапазона [%d, %d]:", a, b);

    for (i = 0; i < size; i++)
    {
        // Элемент подходит, если a <= элемент <= b.
        // Если a > b, условие никогда не выполнится - подходящих элементов не будет.
        if (array[i] >= a && array[i] <= b)
        {
            printf(" %d", array[i]);
            count++; // запоминаем, что хотя бы один элемент нашёлся
        }
    }

    // Если ни один элемент не подошёл - сообщаем об этом
    if (count == 0)
    {
        printf(" таких элементов нет");
    }

    printf("\n"); // переход на новую строку
}

// ---------- Индивидуальное задание (вариант 5) ----------

/*
 * Формирует новый массив, в котором каждое значение исходного массива
 * встречается только один раз (порядок - по первому появлению), и выводит его.
 */
void performIndividualTask(const int array[], int size)
{
    int uniqueArray[MAX_SIZE]; // новый массив без повторений
    int uniqueSize = 0; // сколько элементов уже лежит в новом массиве
    int found; // 1 - значение уже есть в новом массиве, 0 - ещё нет
    int i; // индекс по исходному массиву
    int j; // индекс по новому массиву

    // Идём по исходному массиву слева направо
    for (i = 0; i < size; i++)
    {
        found = 0; // для нового элемента считаем, что такого значения ещё не было

        // Ищем array[i] среди уже добавленных элементов нового массива.
        // Цикл останавливается, как только значение найдено (found станет 1).
        for (j = 0; j < uniqueSize && found == 0; j++)
        {
            if (uniqueArray[j] == array[i])
            {
                found = 1; // такое значение уже есть
            }
        }

        // Если значения в новом массиве ещё нет - добавляем его в конец
        if (found == 0)
        {
            uniqueArray[uniqueSize] = array[i];
            uniqueSize++; // в новом массиве стало на один элемент больше
        }
    }

    // Выводим новый массив. Элементов в нём не больше size <= MAX_SIZE,
    // поэтому выхода за границы массива не будет.
    printf("Массив без повторений:");
    printArray(uniqueArray, uniqueSize);
}
